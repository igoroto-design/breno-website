import { readFileSync, writeFileSync, existsSync, mkdirSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const assetsDir = join(__dirname, "..", "src", "assets");
const outFile = join(__dirname, "..", "src", "generated", "article-card-images.ts");

/** Must match ARTICLE_IMAGES order in App.tsx */
const ORDER = [
  "homem-contemplativo-psicologia.webp",
  "mulher-ansiedade-sessao.webp",
  "psicologo-apoio-suporte.webp",
  "jovem-mulher-sessao-terapia.webp",
  "casal-sessao-psicologia.webp",
  "jovem-homem-psicologia-sessao.webp",
  "mulher-oculos-laptop-ansiedade.webp",
  "homem-escrevendo-diario-terapia.webp",
  "psicologo-conversa-sessao.webp",
  "beneficios-psicoterapia.webp",
  "homem-terapia-online-mesa.webp",
  "mulher-tablet-psicanalise-online.webp",
  "mulher-psicanalise-sessao.webp",
  "homem-expressivo-psicologia.webp",
  "mulher-terapia-online-laptop.webp",
  "homem-sofa-terapia-online.webp",
  "mulher-idosa-psicanalise-sessao.webp",
  "homem-fone-sessao-psicologia.webp",
  "como-funciona-atendimento.webp",
  "jovem-homem-sessao-terapia.webp",
  "mulher-idosa-sorrindo-terapia.webp",
  "homem-mais-velho-oculos-terapia.webp",
  "homem-sessao-psicologia.webp",
  "mulher-idosa-serena-terapia.webp",
  "quando-buscar-psicologo-sinais.webp",
];

const CARD_WIDTH = 640;
const MIN_SOURCE_WIDTH = 700;

let sharp;
try {
  sharp = (await import("sharp")).default;
} catch {
  console.log("⚠ sharp not installed — skipping card image generation");
  process.exit(0);
}

const imports = [];
const arrayEntries = [];

for (let i = 0; i < ORDER.length; i++) {
  const source = ORDER[i];
  const inputPath = join(assetsDir, source);

  if (!existsSync(inputPath)) {
    arrayEntries.push("  undefined,");
    continue;
  }

  const meta = await sharp(readFileSync(inputPath)).metadata();
  if (!meta.width || meta.width <= MIN_SOURCE_WIDTH) {
    arrayEntries.push("  undefined,");
    continue;
  }

  const cardName = source.replace(/\.webp$/, "-card.webp");
  const cardPath = join(assetsDir, cardName);
  const buffer = await sharp(readFileSync(inputPath))
    .resize({ width: CARD_WIDTH, withoutEnlargement: true })
    .webp({ quality: 68, effort: 4 })
    .toBuffer();
  writeFileSync(cardPath, buffer);

  const varName = `card_${i}`;
  imports.push(`import ${varName} from "../assets/${cardName}";`);
  arrayEntries.push(`  ${varName},`);
  console.log(`✓ ${cardName} (${(buffer.length / 1024).toFixed(0)} KB)`);
}

const ts = `// Auto-generated by scripts/generate-card-images.mjs — do not edit
${imports.join("\n")}

export const ARTICLE_CARD_IMAGES: (string | undefined)[] = [
${arrayEntries.join("\n")}
];
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, ts, "utf8");
console.log(`✓ Wrote ${outFile}`);
